export type Screenshot = {
  /** PNG path under /public */
  src: string;
  /** WebP sibling generated by scripts/optimize-images.mjs */
  webp: string;
  /** 600 px wide WebP (for phone-sized display; generated by scripts/optimize-images.mjs) */
  webpSmall: string;
  width: number;
  height: number;
  alt: string;
  /** true while the founder-supplied placeholder is in use */
  sample: boolean;
};

const shot = (file: string, width: number, height: number, alt: string): Screenshot => ({
  src: `/assets/${file}.png`,
  webp: `/assets/${file}.webp`,
  webpSmall: `/assets/${file}-600.webp`,
  width,
  height,
  alt,
  sample: true,
});

